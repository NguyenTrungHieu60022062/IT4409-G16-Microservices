-- Auth Service schema v1.
-- Viết bằng SQL chuẩn để chạy được trên cả PostgreSQL (thật) và H2 MODE=PostgreSQL (local/test).

CREATE TABLE users (
    id                  UUID         PRIMARY KEY,
    -- Email luôn được chuẩn hoá (trim + lowercase) trước khi lưu, nên UNIQUE ở đây là đủ.
    email               VARCHAR(254) NOT NULL,
    -- Chuỗi dạng "{argon2}$argon2id$v=19$m=19456,t=2,p=1$<salt>$<hash>" — KHÔNG BAO GIỜ lưu mật khẩu gốc.
    password_hash       VARCHAR(255) NOT NULL,
    role                VARCHAR(20)  NOT NULL,
    status              VARCHAR(20)  NOT NULL,
    created_at          TIMESTAMP WITH TIME ZONE NOT NULL,
    -- Access token có iat trước mốc này sẽ bị từ chối (đổi mật khẩu = vô hiệu hoá token cũ).
    password_changed_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_users_email UNIQUE (email),
    CONSTRAINT ck_users_role CHECK (role IN ('CUSTOMER', 'ADMIN')),
    CONSTRAINT ck_users_status CHECK (status IN ('ACTIVE', 'DISABLED'))
);

-- Mỗi lần refresh sinh 1 dòng mới; các dòng cùng family_id là 1 "phiên đăng nhập" trên 1 thiết bị.
CREATE TABLE refresh_tokens (
    id                 UUID         PRIMARY KEY,
    user_id            UUID         NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    family_id          UUID         NOT NULL,
    -- Chỉ lưu SHA-256 (hex) của token. Lộ DB cũng không dùng lại được token.
    token_hash         VARCHAR(64)  NOT NULL,
    remember_me        BOOLEAN      NOT NULL,
    session_started_at TIMESTAMP WITH TIME ZONE NOT NULL,
    created_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    -- Hạn tuyệt đối của cả phiên; xoay vòng token KHÔNG kéo dài mốc này.
    expires_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    revoked_at         TIMESTAMP WITH TIME ZONE,
    revoke_reason      VARCHAR(30),
    replaced_by        UUID,
    created_ip         VARCHAR(45),
    user_agent         VARCHAR(255),
    CONSTRAINT uq_refresh_tokens_hash UNIQUE (token_hash)
);
CREATE INDEX idx_refresh_tokens_user ON refresh_tokens (user_id);
CREATE INDEX idx_refresh_tokens_family ON refresh_tokens (family_id);

CREATE TABLE auth_audit_log (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     UUID,
    event       VARCHAR(40)  NOT NULL,
    -- Email đã che bớt (vd "ng***@gmail.com"), không lưu nguyên văn email người lạ nhập vào.
    subject     VARCHAR(254),
    ip          VARCHAR(45),
    user_agent  VARCHAR(255),
    success     BOOLEAN      NOT NULL,
    occurred_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_audit_user ON auth_audit_log (user_id);
